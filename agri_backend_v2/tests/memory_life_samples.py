def life_samples(count=3000, seed=20261024):
    """生成不同正文与明确场景；随机种子固定后可复现同一批压力语料。"""
    rng = random.Random(seed)
    pool = []
    for topic, (contexts, statements) in TOPICS.items():
        for context in contexts.split("|"):
            for statement in statements.split("|"):
                lead = (
                    context
                    if context.endswith("时")
                    or context.startswith(
                        ("周末", "节假日", "午后", "休假", "旅行的空档")
                    )
                    else context + "时"
                )
                text = f"{lead}，我{statement}。"
                pool.append(
                    {
                        "key": f"{topic}.{context}",
                        "text": text,
                        "conditions": [context],
                        "category": "work" if topic == "工作习惯" else "preference",
                        "temporal_scope": "current",
                        "time_evidence": "",
                    }
                )
    rng.shuffle(pool)
    anchors = [
        {
            "key": "咖啡.拿铁",
            "text": "我喝拿铁时更喜欢燕麦奶，而且不喜欢加糖。",
            "conditions": ["喝拿铁"],
            "category": "preference",
            "temporal_scope": "current",
            "time_evidence": "",
            "facts": [
                ("拿铁.奶的种类", "我喝拿铁时更喜欢燕麦奶"),
                ("拿铁.加糖", "我喝拿铁时不喜欢加糖"),
            ],
        },
        {
            "key": "休闲.电影座位",
            "text": "周末去看电影时，我更喜欢坐靠过道的位置。",
            "conditions": ["周末看电影"],
            "category": "preference",
            "temporal_scope": "current",
            "time_evidence": "",
        },
        {
            "key": "习惯.照片归档",
            "text": "我整理照片时习惯先按年份建文件夹，再按月份分类。",
            "conditions": ["整理照片"],
            "category": "general",
            "temporal_scope": "current",
            "time_evidence": "",
        },
    ]
    history = []
    events = [
        "做了一个手工陶杯，喜欢釉面慢慢变亮的过程",
        "去看了一场小型摄影展，喜欢其中的街头光影",
        "烤了一盘燕麦饼干，觉得加一点肉桂很香",
        "参加了一次植物拓印活动，觉得叶脉的纹路很有趣",
        "在旧书店找到一本散文集，喜欢里面的旅行随笔",
        "和朋友一起拼完一幅风景拼图，喜欢慢慢完成它的感觉",
        "散步时拍了一组树影照片，喜欢午后的柔和光线",
        "尝试了手工装订，喜欢线装本平摊时的样子",
    ]
    for index in range(min(300, count // 10)):
        date = datetime(2024, 1, 1, tzinfo=UTC) + timedelta(days=index * 3)
        evidence = date.strftime("%Y年%m月%d日")
        history.append(
            {
                "key": "生活经历." + date.date().isoformat(),
                "text": f"{evidence}，我{rng.choice(events)}。",
                "conditions": [],
                "category": "general",
                "temporal_scope": "historical",
                "time_evidence": evidence,
            }
        )
    rows = anchors + history + pool[: count - len(anchors) - len(history)]
    assert len(rows) == count and len({r["text"] for r in rows}) == count
    rng.shuffle(rows)
    return rows
